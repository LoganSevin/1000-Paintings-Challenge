def dedupe(rows: list[dict]) -> list[dict]:
    seen = set()
    out = []
    for r in rows:
        if r["id"] in seen or r["id"].endswith("-dup"):
            continue
        seen.add(r["id"])
        out.append(r)
    out.sort(key=lambda x: (x["kind"], x["genre"], x["name"].lower()))
    return out


