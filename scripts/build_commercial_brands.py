def dedupe(brands: list[dict]) -> list[dict]:
    seen = set()
    out = []
    skip_suffixes = ("-dup", "-dup-skip", "-rest", "-skip")
    for b in brands:
        bid = b["id"]
        if bid.endswith(skip_suffixes) or bid in seen:
            continue
        # also skip obvious junk
        if "dup" in bid and bid not in seen:
            if any(x in bid for x in ("-dup", "dup-skip")):
                continue
        if bid in seen:
            continue
        seen.add(bid)
        # normalize products
        prods = b.get("products") or []
        b["products"] = [str(p).strip() for p in prods if str(p).strip()][:8]
        if not b["products"]:
            b["products"] = [f"{b['name']} products and services"]
        out.append(b)
    out.sort(key=lambda x: (x["category"], x["name"].lower()))
    return out


