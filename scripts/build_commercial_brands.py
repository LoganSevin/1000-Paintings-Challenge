def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:64] or "brand"


def B(name: str, domain: str, category: str, products: list[str], bid: str | None = None):
    return {
        "id": bid or slug(name),
        "name": name,
        "domain": domain,
        "category": category,
        "products": products,
    }


# (name, domain, products...) — category applied by section
def pack(cat: str, rows: list[tuple]) -> list[dict]:
    out = []
    for row in rows:
        if len(row) == 3:
            name, domain, products = row
            bid = None
        else:
            name, domain, products, bid = row
        out.append(B(name, domain, cat, list(products), bid))
    return out


